/**
 * Cuts the voice A/B for the PV out of the owner's recording and writes the two WAVs the
 * composition plays.
 *
 * The source carries 1.57 s of lead-in, 3.36 s of dead air between the two takes, a 1.28 s
 * pause inside the converted take, and a trailing tail. Those are trimmed here. The converted
 * take also sits 11 LU above the original, which would make the A/B a loudness comparison
 * rather than a voice comparison, so both are matched to one target with a flat gain.
 */
import { execFileSync, spawnSync } from "node:child_process";
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const PUBLIC = resolve(HERE, "../public");
const SOURCE = "raw/voice_source.mp3";
const RATE = 48000;

/** [from, to] in seconds of the source. More than one pair is concatenated. */
const TAKES = {
  original: { windows: [[1.506, 4.945]], gainDb: 5.6 },
  converted: { windows: [[8.186, 8.963], [9.942, 12.441]], gainDb: -5.5 },
};

function render(take, destination) {
  const chain = take.windows
    .map(([from, to], i) => `[0:a]atrim=${from}:${to},asetpts=PTS-STARTPTS[s${i}]`)
    .join(";");
  const filter = `${chain};${take.windows.map((_, i) => `[s${i}]`).join("")}concat=n=${take.windows.length}:v=0:a=1[v];[v]volume=${take.gainDb}dB[out]`;
  execFileSync(
    "ffmpeg",
    ["-v", "error", "-y", "-i", resolve(PUBLIC, SOURCE), "-filter_complex", filter,
     "-map", "[out]", "-ac", "1", "-ar", String(RATE), "-c:a", "pcm_s16le", destination],
    { stdio: ["ignore", "ignore", "inherit"] },
  );
  return destination;
}

/** ffmpeg reports loudnorm's measurement on stderr, not stdout. */
function probe(path) {
  return spawnSync(
    "ffmpeg", ["-hide_banner", "-i", path, "-af", "loudnorm=print_format=summary", "-f", "null", "-"],
    { encoding: "utf8" },
  ).stderr;
}

mkdirSync(resolve(PUBLIC, "audio"), { recursive: true });
const written = [];
for (const [name, take] of Object.entries(TAKES)) {
  const destination = resolve(PUBLIC, `audio/voice_demo_${name}.wav`);
  render(take, destination);
  const seconds = take.windows.reduce((total, [from, to]) => total + (to - from), 0);
  written.push({ name, file: `audio/voice_demo_${name}.wav`, seconds: Number(seconds.toFixed(3)),
    frames: Math.ceil(seconds * 60), gainDb: take.gainDb, windows: take.windows });
}

writeFileSync(
  resolve(PUBLIC, "audio/voice_demo.json"),
  JSON.stringify({
    kind: "Owner-supplied recording, trimmed and loudness matched. Not generated by this repo.",
    source: SOURCE,
    targetIntegratedLoudness: "both takes brought to -17.0 LUFS with a flat gain",
    trims: "1.57 s lead-in, 3.36 s gap between the takes, 1.28 s pause inside the converted take, trailing tail",
    takes: written,
  }, null, 1),
);

for (const take of written) {
  const measured = probe(resolve(PUBLIC, take.file)).match(/Input Integrated:\s*(-?\d+\.?\d*) LUFS/);
  console.log(`${take.file}  ${take.seconds}s  ${take.frames}f  ${measured ? `${measured[1]} LUFS` : ""}`);
}
